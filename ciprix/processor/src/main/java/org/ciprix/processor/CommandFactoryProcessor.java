package org.ciprix.processor;

import com.google.auto.service.AutoService;
import com.squareup.javapoet.ClassName;
import com.squareup.javapoet.JavaFile;
import com.squareup.javapoet.MethodSpec;
import com.squareup.javapoet.ParameterizedTypeName;
import com.squareup.javapoet.TypeName;
import com.squareup.javapoet.TypeSpec;
import java.io.IOException;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.function.Supplier;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Processor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.annotation.processing.SupportedOptions;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.AnnotationMirror;
import javax.lang.model.element.AnnotationValue;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeKind;
import javax.lang.model.type.TypeMirror;
import javax.tools.Diagnostic;

/**
 * Generates {@code <Subsystem>Commands} for every class annotated with {@code
 * org.ciprix.annotations.AutoCommandFactory}.
 *
 * <p>The annotation is read through mirrors, so this processor has no compile-time dependency on
 * the library that declares it.
 */
@AutoService(Processor.class)
@SupportedAnnotationTypes(CommandFactoryProcessor.ANNOTATION)
@SupportedOptions(CommandFactoryProcessor.SUPERSTRUCTURE_OPTION)
public class CommandFactoryProcessor extends AbstractProcessor {

  static final String ANNOTATION = "org.ciprix.annotations.AutoCommandFactory";

  /** Compiler option ({@code -Aciprix.superStructure=...}) with the SuperStructure class name. */
  static final String SUPERSTRUCTURE_OPTION = "ciprix.superStructure";

  private static final String DEFAULT_SUPERSTRUCTURE =
      "frc.robot.subsystems.superstructure.SuperStructure";

  private static final ClassName COMMAND_CLASS =
      ClassName.get("edu.wpi.first.wpilibj2.command", "Command");
  private static final ClassName COMMANDS_CLASS =
      ClassName.get("edu.wpi.first.wpilibj2.command", "Commands");

  @Override
  public SourceVersion getSupportedSourceVersion() {
    return SourceVersion.latestSupported();
  }

  @Override
  public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
    for (TypeElement annotation : annotations) {
      for (Element element : roundEnv.getElementsAnnotatedWith(annotation)) {
        if (element.getKind() != ElementKind.CLASS) {
          error(element, "@AutoCommandFactory can only be used on classes");
          continue;
        }
        TypeElement subsystemElement = (TypeElement) element;
        AnnotationMirror mirror = findAnnotation(subsystemElement);
        if (mirror == null) {
          continue;
        }

        TypeElement enumElement = asTypeElement(getValue(mirror, "requestEnum"));
        if (enumElement == null || enumElement.getKind() != ElementKind.ENUM) {
          error(subsystemElement, "requestEnum of @AutoCommandFactory must be an enum class");
          continue;
        }

        generateFactoryClass(subsystemElement, enumElement, resolveSuperStructure(mirror));
      }
    }
    return true;
  }

  private void generateFactoryClass(
      TypeElement subsystemElement, TypeElement enumElement, TypeElement superStructureElement) {
    String packageName =
        processingEnv
            .getElementUtils()
            .getPackageOf(subsystemElement)
            .getQualifiedName()
            .toString();
    String subsystemName = subsystemElement.getSimpleName().toString();
    String factoryName = subsystemName + "Commands";
    String param = decapitalize(subsystemName);

    ClassName subsystemClassName = ClassName.get(subsystemElement);
    ClassName enumClassName = ClassName.get(enumElement);
    TypeName requestSupplier =
        ParameterizedTypeName.get(ClassName.get(Supplier.class), enumClassName);

    TypeSpec.Builder classBuilder =
        TypeSpec.classBuilder(factoryName)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addOriginatingElement(subsystemElement)
            .addJavadoc(
                "Command factory of {@link $T}, generated by the Ciprix annotation processor.\n"
                    + "Do not edit: it is rewritten on every build.\n",
                subsystemClassName)
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());

    // Relay (default command): copies the request computed by the SuperStructure every cycle.
    classBuilder.addMethod(
        MethodSpec.methodBuilder("defaultCommand")
            .addJavadoc(
                "Relay used as the default command: every cycle it copies the request given by\n"
                    + "{@code requestSource} (normally the SuperStructure) into the subsystem.\n")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .returns(COMMAND_CLASS)
            .addParameter(requestSupplier, "requestSource")
            .addParameter(subsystemClassName, param)
            .addStatement(
                "return $T.run(() -> $L.setRequest(requestSource.get()), $L)\n.withName($S)",
                COMMANDS_CLASS,
                param,
                param,
                subsystemName + " Default Relay")
            .build());

    if (superStructureElement != null) {
      classBuilder.addMethod(
          MethodSpec.methodBuilder("defaultCommand")
              .addJavadoc(
                  "Relay used as the default command: every cycle it copies {@code\n"
                      + "superStructure.get$LRequest()} into the subsystem.\n",
                  subsystemName)
              .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
              .returns(COMMAND_CLASS)
              .addParameter(ClassName.get(superStructureElement), "superStructure")
              .addParameter(subsystemClassName, param)
              .addStatement(
                  "return defaultCommand(superStructure::get$LRequest, $L)", subsystemName, param)
              .build());
    }

    // Manual override (copilot backup). A StateSubsystem has override(request), which lasts one
    // cycle and never touches the request of the SuperStructure, so the command needs no
    // requirement and the relay keeps running underneath. Any other class falls back to
    // setRequest with the subsystem as requirement, which interrupts the relay while held.
    final boolean transientOverride = hasMethod(subsystemElement, "override", 1);
    final String overrideDoc =
        transientOverride
            ? "The relay keeps running underneath, so the subsystem goes back to the request of\n"
                + "the SuperStructure by itself on the cycle after the command ends.\n"
            : "It interrupts only the relay of this subsystem, which resumes when the command\n"
                + "ends.\n";

    MethodSpec.Builder override =
        MethodSpec.methodBuilder("override")
            .addJavadoc(
                "Manual override: follows {@code request} while the command is scheduled.\n"
                    + overrideDoc)
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .returns(COMMAND_CLASS)
            .addParameter(subsystemClassName, param)
            .addParameter(enumClassName, "request");
    if (transientOverride) {
      override.addStatement(
          "return $T.run(() -> $L.override(request))\n.withName($S + request)",
          COMMANDS_CLASS,
          param,
          subsystemName + " Override ");
    } else {
      override.addStatement(
          "return $T.run(() -> $L.setRequest(request), $L)\n.withName($S + request)",
          COMMANDS_CLASS,
          param,
          param,
          subsystemName + " Override ");
    }
    classBuilder.addMethod(override.build());

    // One manual override per request.
    for (Element enclosed : enumElement.getEnclosedElements()) {
      if (enclosed.getKind() != ElementKind.ENUM_CONSTANT) {
        continue;
      }
      String enumValue = enclosed.getSimpleName().toString();
      MethodSpec.Builder method =
          MethodSpec.methodBuilder(methodNameFor(enumValue))
              .addJavadoc(
                  "Manual override: follows {@link $T#$L} while the command is scheduled.\n",
                  enumClassName,
                  enumValue)
              .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
              .returns(COMMAND_CLASS)
              .addParameter(subsystemClassName, param);
      if (transientOverride) {
        method.addStatement(
            "return $T.run(() -> $L.override($T.$L))\n.withName($S)",
            COMMANDS_CLASS,
            param,
            enumClassName,
            enumValue,
            subsystemName + " Override " + enumValue);
      } else {
        method.addStatement(
            "return $T.run(() -> $L.setRequest($T.$L), $L)\n.withName($S)",
            COMMANDS_CLASS,
            param,
            enumClassName,
            enumValue,
            param,
            subsystemName + " Override " + enumValue);
      }
      classBuilder.addMethod(method.build());
    }

    JavaFile javaFile = JavaFile.builder(packageName, classBuilder.build()).indent("  ").build();

    try {
      javaFile.writeTo(processingEnv.getFiler());
    } catch (IOException e) {
      error(subsystemElement, "Failed to write generated factory " + factoryName + ": " + e);
    }
  }

  /**
   * Name of the override method of a request: the constant in lower case ({@code RUN_SLOW} becomes
   * {@code run_slow}). Constants that would produce a Java keyword ({@code DEFAULT}, {@code NEW},
   * ...) or clash with the fixed methods get the {@code Request} suffix.
   */
  static String methodNameFor(String enumValue) {
    String name = enumValue.toLowerCase(Locale.ROOT);
    if (SourceVersion.isKeyword(name) || name.equals("override") || name.equals("defaultcommand")) {
      return name + "Request";
    }
    return name;
  }

  private static String decapitalize(String name) {
    String lower = name.toLowerCase(Locale.ROOT);
    return SourceVersion.isKeyword(lower) ? lower + "Subsystem" : lower;
  }

  /** True when {@code type} has (or inherits) a public instance method with that name and arity. */
  private boolean hasMethod(TypeElement type, String name, int parameterCount) {
    for (Element member : processingEnv.getElementUtils().getAllMembers(type)) {
      if (member.getKind() == ElementKind.METHOD
          && member.getSimpleName().contentEquals(name)
          && member.getModifiers().contains(Modifier.PUBLIC)
          && !member.getModifiers().contains(Modifier.STATIC)
          && ((ExecutableElement) member).getParameters().size() == parameterCount) {
        return true;
      }
    }
    return false;
  }

  private TypeElement resolveSuperStructure(AnnotationMirror mirror) {
    TypeElement explicit = asTypeElement(getValue(mirror, "superStructure"));
    if (explicit != null) {
      return explicit;
    }
    String configured = processingEnv.getOptions().get(SUPERSTRUCTURE_OPTION);
    String name = configured == null || configured.isBlank() ? DEFAULT_SUPERSTRUCTURE : configured;
    return processingEnv.getElementUtils().getTypeElement(name);
  }

  private AnnotationMirror findAnnotation(TypeElement element) {
    for (AnnotationMirror mirror : element.getAnnotationMirrors()) {
      Element annotationElement = mirror.getAnnotationType().asElement();
      if (annotationElement instanceof TypeElement type
          && type.getQualifiedName().contentEquals(ANNOTATION)) {
        return mirror;
      }
    }
    return null;
  }

  private AnnotationValue getValue(AnnotationMirror mirror, String name) {
    for (Map.Entry<? extends ExecutableElement, ? extends AnnotationValue> entry :
        mirror.getElementValues().entrySet()) {
      if (entry.getKey().getSimpleName().contentEquals(name)) {
        return entry.getValue();
      }
    }
    return null;
  }

  /** Resolves a {@code Class} annotation value to its element ({@code null} for void). */
  private TypeElement asTypeElement(AnnotationValue value) {
    if (value == null || !(value.getValue() instanceof TypeMirror type)) {
      return null;
    }
    if (type.getKind() != TypeKind.DECLARED) {
      return null;
    }
    Element element = ((DeclaredType) type).asElement();
    return element instanceof TypeElement typeElement ? typeElement : null;
  }

  private void error(Element element, String message) {
    processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, message, element);
  }
}
